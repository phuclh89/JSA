CREATE TABLE JSA_TRANSLATION (
  TRANSLATION_ID NUMBER(19) NOT NULL,
  JSA_ID NUMBER(19) NOT NULL,
  SOURCE_JSA_VERSION_ID NUMBER(19) NOT NULL,
  SOURCE_LANGUAGE_ID NUMBER(19) NOT NULL,
  TARGET_LANGUAGE_ID NUMBER(19) NOT NULL,
  PREVIOUS_TRANSLATION_ID NUMBER(19),
  OWNER_SITE_ID NUMBER(19) NOT NULL,
  RIG_ID NUMBER(19) NOT NULL,
  DEPARTMENT_ID NUMBER(19) NOT NULL,
  TRANSLATION_STATUS VARCHAR2(30 CHAR) DEFAULT 'ASSIGNED' NOT NULL,
  TRANSLATION_CYCLE NUMBER(10) DEFAULT 1 NOT NULL,
  TRANSLATOR_USER_ID NUMBER(19) NOT NULL,
  TRANSLATOR_USERNAME VARCHAR2(255 CHAR) NOT NULL,
  TRANSLATOR_DISPLAY_NAME VARCHAR2(255 CHAR) NOT NULL,
  CURRENT_ASSIGNEE_USER_ID NUMBER(19),
  STC_REVIEWER_USER_ID NUMBER(19),
  STC_REVIEWER_USERNAME VARCHAR2(255 CHAR),
  STC_REVIEWER_DISPLAY_NAME VARCHAR2(255 CHAR),
  ASSIGNED_BY_USER_ID NUMBER(19) NOT NULL,
  ASSIGNED_BY_USERNAME VARCHAR2(255 CHAR) NOT NULL,
  ASSIGNED_BY_DISPLAY_NAME VARCHAR2(255 CHAR) NOT NULL,
  ASSIGNED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  SUBMITTED_AT TIMESTAMP(6),
  PUBLISHED_AT TIMESTAMP(6),
  PUBLISHED_BY_USER_ID NUMBER(19),
  PUBLISHED_BY_USERNAME VARCHAR2(255 CHAR),
  OUTDATED_AT TIMESTAMP(6),
  REPLACEMENT_JSA_VERSION_ID NUMBER(19),
  INVENTORY_LOCKED_FLAG CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
  SOURCE_CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
  TRANSLATED_CONTENT_HASH VARCHAR2(64 CHAR),
  CREATED_SITE_ID NUMBER(19) NOT NULL,
  UPDATED_SITE_ID NUMBER(19) NOT NULL,
  CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY VARCHAR2(255 CHAR) NOT NULL,
  UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR2(255 CHAR) NOT NULL,
  ROW_VERSION NUMBER(19) DEFAULT 1 NOT NULL,
  CONSTRAINT PK_JSA_TRANSLATION PRIMARY KEY (TRANSLATION_ID),
  CONSTRAINT UK_JSA_TRANSL_SOURCE_LANG UNIQUE (SOURCE_JSA_VERSION_ID,TARGET_LANGUAGE_ID),
  CONSTRAINT FK_JSA_TRANSL_MASTER FOREIGN KEY (JSA_ID) REFERENCES JSA_MASTER(JSA_ID),
  CONSTRAINT FK_JSA_TRANSL_SOURCE FOREIGN KEY (SOURCE_JSA_VERSION_ID,JSA_ID)
    REFERENCES JSA_VERSION(JSA_VERSION_ID,JSA_ID),
  CONSTRAINT FK_JSA_TRANSL_SRC_LANG FOREIGN KEY (SOURCE_LANGUAGE_ID) REFERENCES SYS_LANGUAGE(LANGUAGE_ID),
  CONSTRAINT FK_JSA_TRANSL_TGT_LANG FOREIGN KEY (TARGET_LANGUAGE_ID) REFERENCES SYS_LANGUAGE(LANGUAGE_ID),
  CONSTRAINT FK_JSA_TRANSL_PREVIOUS FOREIGN KEY (PREVIOUS_TRANSLATION_ID) REFERENCES JSA_TRANSLATION(TRANSLATION_ID),
  CONSTRAINT FK_JSA_TRANSL_SITE FOREIGN KEY (OWNER_SITE_ID) REFERENCES SYS_SITE(SITE_ID),
  CONSTRAINT FK_JSA_TRANSL_RIG FOREIGN KEY (RIG_ID,OWNER_SITE_ID) REFERENCES SYS_RIG(RIG_ID,SITE_ID),
  CONSTRAINT FK_JSA_TRANSL_DEPT FOREIGN KEY (DEPARTMENT_ID,RIG_ID) REFERENCES SYS_DEPARTMENT(DEPARTMENT_ID,RIG_ID),
  CONSTRAINT FK_JSA_TRANSL_TRANSLATOR FOREIGN KEY (TRANSLATOR_USER_ID) REFERENCES SYS_USER(USER_ID),
  CONSTRAINT FK_JSA_TRANSL_ASSIGNEE FOREIGN KEY (CURRENT_ASSIGNEE_USER_ID) REFERENCES SYS_USER(USER_ID),
  CONSTRAINT FK_JSA_TRANSL_STC FOREIGN KEY (STC_REVIEWER_USER_ID) REFERENCES SYS_USER(USER_ID),
  CONSTRAINT FK_JSA_TRANSL_ASSIGNER FOREIGN KEY (ASSIGNED_BY_USER_ID) REFERENCES SYS_USER(USER_ID),
  CONSTRAINT FK_JSA_TRANSL_PUBLISHER FOREIGN KEY (PUBLISHED_BY_USER_ID) REFERENCES SYS_USER(USER_ID),
  CONSTRAINT FK_JSA_TRANSL_REPLACE FOREIGN KEY (REPLACEMENT_JSA_VERSION_ID) REFERENCES JSA_VERSION(JSA_VERSION_ID),
  CONSTRAINT FK_JSA_TRANSL_CREATED_SITE FOREIGN KEY (CREATED_SITE_ID) REFERENCES SYS_SITE(SITE_ID),
  CONSTRAINT FK_JSA_TRANSL_UPDATED_SITE FOREIGN KEY (UPDATED_SITE_ID) REFERENCES SYS_SITE(SITE_ID),
  CONSTRAINT CHK_JSA_TRANSL_STATUS CHECK (TRANSLATION_STATUS IN
    ('ASSIGNED','IN_TRANSLATION','STC_REVIEW','RETURNED','PUBLISHED','OUTDATED')),
  CONSTRAINT CHK_JSA_TRANSL_LANG CHECK (SOURCE_LANGUAGE_ID<>TARGET_LANGUAGE_ID),
  CONSTRAINT CHK_JSA_TRANSL_CYCLE CHECK (TRANSLATION_CYCLE>=1),
  CONSTRAINT CHK_JSA_TRANSL_INV CHECK (INVENTORY_LOCKED_FLAG IN ('Y','N')),
  CONSTRAINT CHK_JSA_TRANSL_HASH CHECK
    (LENGTH(SOURCE_CONTENT_HASH)=64 AND (TRANSLATED_CONTENT_HASH IS NULL OR LENGTH(TRANSLATED_CONTENT_HASH)=64)),
  CONSTRAINT CHK_JSA_TRANSL_PUBLISHED CHECK
    (TRANSLATION_STATUS<>'PUBLISHED' OR
      (PUBLISHED_AT IS NOT NULL AND PUBLISHED_BY_USER_ID IS NOT NULL AND CURRENT_ASSIGNEE_USER_ID IS NULL)),
  CONSTRAINT CHK_JSA_TRANSL_OUTDATED CHECK
    (TRANSLATION_STATUS<>'OUTDATED' OR
      (OUTDATED_AT IS NOT NULL AND REPLACEMENT_JSA_VERSION_ID IS NOT NULL AND CURRENT_ASSIGNEE_USER_ID IS NULL)),
  CONSTRAINT CHK_JSA_TRANSL_ROW_VER CHECK (ROW_VERSION>=1)
);

