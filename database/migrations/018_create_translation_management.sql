CREATE OR REPLACE PROCEDURE JSA_ASSERT_TRANSL_MUTABLE(P_TRANSLATION_ID NUMBER) AS
  V_STATUS JSA_TRANSLATION.TRANSLATION_STATUS%TYPE;
BEGIN
  SELECT TRANSLATION_STATUS INTO V_STATUS
    FROM JSA_TRANSLATION WHERE TRANSLATION_ID=P_TRANSLATION_ID;
  IF V_STATUS NOT IN ('ASSIGNED','IN_TRANSLATION','RETURNED') THEN
    RAISE_APPLICATION_ERROR(-20071,'Translation content is immutable in the current status');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_JSA_TRANSL_SEG_MUTABLE
BEFORE INSERT OR UPDATE OR DELETE ON JSA_TRANSLATION_SEGMENT FOR EACH ROW
DECLARE V_LOCKED CHAR(1); V_ID NUMBER;
BEGIN
  V_ID := COALESCE(:NEW.TRANSLATION_ID,:OLD.TRANSLATION_ID);
  JSA_ASSERT_TRANSL_MUTABLE(V_ID);
  SELECT INVENTORY_LOCKED_FLAG INTO V_LOCKED FROM JSA_TRANSLATION WHERE TRANSLATION_ID=V_ID;
  IF INSERTING AND V_LOCKED='Y' THEN
    RAISE_APPLICATION_ERROR(-20072,'Translation segment inventory is immutable');
  END IF;
  IF DELETING THEN
    RAISE_APPLICATION_ERROR(-20072,'Translation segment inventory is immutable');
  END IF;
  IF UPDATING AND
    (:NEW.TRANSLATION_ID<>:OLD.TRANSLATION_ID OR :NEW.ENTITY_TYPE<>:OLD.ENTITY_TYPE OR
     :NEW.SOURCE_ENTITY_ID<>:OLD.SOURCE_ENTITY_ID OR :NEW.SOURCE_LOGICAL_KEY<>:OLD.SOURCE_LOGICAL_KEY OR
     :NEW.FIELD_CODE<>:OLD.FIELD_CODE OR :NEW.SECTION_CODE<>:OLD.SECTION_CODE OR
     :NEW.DISPLAY_ORDER<>:OLD.DISPLAY_ORDER OR :NEW.REQUIRED_FLAG<>:OLD.REQUIRED_FLAG OR
     DBMS_LOB.COMPARE(:NEW.SOURCE_TEXT,:OLD.SOURCE_TEXT)<>0 OR :NEW.SOURCE_TEXT_HASH<>:OLD.SOURCE_TEXT_HASH) THEN
    RAISE_APPLICATION_ERROR(-20073,'Translation source snapshot is immutable');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_JSA_TRANSL_FINAL_IMMUT
BEFORE UPDATE OR DELETE ON JSA_TRANSLATION FOR EACH ROW
BEGIN
  IF DELETING THEN
    RAISE_APPLICATION_ERROR(-20074,'Translation history cannot be deleted');
  END IF;
  IF :OLD.TRANSLATION_STATUS IN ('PUBLISHED','OUTDATED') THEN
    IF NOT (:OLD.TRANSLATION_STATUS='PUBLISHED' AND :NEW.TRANSLATION_STATUS='OUTDATED'
      AND :NEW.OUTDATED_AT IS NOT NULL AND :NEW.REPLACEMENT_JSA_VERSION_ID IS NOT NULL) THEN
      RAISE_APPLICATION_ERROR(-20075,'Published or Outdated translation is immutable');
    END IF;
  END IF;
  IF :NEW.SOURCE_JSA_VERSION_ID<>:OLD.SOURCE_JSA_VERSION_ID OR
     :NEW.TARGET_LANGUAGE_ID<>:OLD.TARGET_LANGUAGE_ID OR :NEW.JSA_ID<>:OLD.JSA_ID OR
     :NEW.SOURCE_CONTENT_HASH<>:OLD.SOURCE_CONTENT_HASH OR
     NVL(:NEW.PREVIOUS_TRANSLATION_ID,-1)<>NVL(:OLD.PREVIOUS_TRANSLATION_ID,-1) THEN
    RAISE_APPLICATION_ERROR(-20076,'Translation identity is immutable');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_JSA_TRANSL_ACTION_IMMUT
BEFORE UPDATE OR DELETE ON JSA_TRANSLATION_ACTION
BEGIN
  RAISE_APPLICATION_ERROR(-20077,'Translation action evidence is append-only');
END;
